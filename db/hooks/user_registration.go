package hooks

import (
	validation "github.com/go-ozzo/ozzo-validation/v4"
	"github.com/pocketbase/pocketbase/core"
)

// GenerateUserRecordIdentity leaves ordinary registration IDs to PocketBase.
// Administrative imports retain explicitly chosen IDs.
func GenerateUserRecordIdentity() func(*core.RecordRequestEvent) error {
	return func(e *core.RecordRequestEvent) error {
		if e.Record.Id != "" && (e.Auth == nil || !e.Auth.IsSuperuser()) {
			return validation.Errors{"id": validation.NewError("validation_not_allowed", "Record IDs are generated by the server.")}
		}
		return e.Next()
	}
}
